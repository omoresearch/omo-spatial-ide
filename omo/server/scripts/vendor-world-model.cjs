#!/usr/bin/env node
'use strict';
// Re-vendor the shared contracts (common/world-model.ts, player-state.ts, presence-protocol.ts) into
// server/vendor/*.cjs so the room server runs standalone (no Theia build). Writes a sha256 note.
// Usage: node omo/server/scripts/vendor-world-model.cjs [--check]
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const SRC = path.resolve(__dirname, '../../extension/src/common');
const OUT = path.resolve(__dirname, '../vendor');
const FILES = [['world-model.ts', 'world-model.cjs'], ['player-state.ts', 'player-state.cjs'], ['presence-protocol.ts', 'presence-protocol.cjs']];
const sha = s => crypto.createHash('sha256').update(s).digest('hex');
function sources() { return FILES.map(([src, out]) => ({ src, out, text: fs.readFileSync(path.join(SRC, src), 'utf8') })); }
if (process.argv.includes('--check')) {
    const hashes = JSON.parse(fs.readFileSync(path.join(OUT, 'VENDOR.json'), 'utf8')).sources;
    let ok = true;
    for (const f of sources()) { const h = sha(f.text); if (hashes[f.src] !== h) { ok = false; console.log(`STALE ${f.src}: vendored ${hashes[f.src]} != source ${h}`); } }
    console.log(ok ? 'vendored world model matches source' : 'run: node omo/server/scripts/vendor-world-model.cjs');
    process.exit(ok ? 0 : 1);
}
const ts = require(require.resolve('typescript', { paths: [path.resolve(__dirname, '../..')] }));
const meta = { note: 'GENERATED by scripts/vendor-world-model.cjs from omo/extension/src/common. Do not edit; re-run the script.', generatedAt: new Date().toISOString(), sources: {} };
for (const f of sources()) {
    let js = ts.transpileModule(f.text, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, strict: true }, fileName: f.src }).outputText;
    js = js.replace(/require\("\.\/player-state"\)/g, 'require("./player-state.cjs")');
    meta.sources[f.src] = sha(f.text);
    fs.writeFileSync(path.join(OUT, f.out), `// GENERATED from omo/extension/src/common/${f.src} (sha256 ${meta.sources[f.src]}). Do not edit.\n${js}`);
}
fs.writeFileSync(path.join(OUT, 'VENDOR.json'), JSON.stringify(meta, null, 2) + '\n');
console.log('vendored', Object.keys(meta.sources).join(', '));
