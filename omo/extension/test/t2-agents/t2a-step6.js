module.exports = async (ctx) => {
    const { page, pause, fs } = ctx;
    const S = '/home/harry/.hermes/profiles/omo-dev/cache/scratch/t2a-explore';
    await require('./t2a-step1.js')(ctx);
    const out = {};
    const argvCount = () => fs.readFileSync(S + '/fake/argv.jsonl', 'utf8').trim().split('\n').filter(Boolean).length;
    out.stdinBefore = fs.readFileSync(S + '/fake/stdin.jsonl', 'utf8');
    await page.click('[data-testid="agents-toggle"]');
    await page.waitForSelector('[data-testid="agent-check-run"]');
    const n0 = argvCount();
    await page.click('[data-testid="agent-check-run"]');
    await page.waitForSelector('[data-testid="agent-check-confirm"]', { timeout: 10000 });
    out.confirm = await page.$eval('[data-testid="agent-check-confirm"]', e => e.innerText);
    await pause(2000);
    out.startedBeforeConfirm = argvCount() - n0;
    await page.screenshot({ path: __dirname + '/t2a-check-confirm.png' });
    await page.click('[data-testid="agent-check-confirm-yes"]');
    await page.waitForSelector('[data-testid="agent-check"][data-phase="observing"]', { timeout: 60000 }).catch(e => out.obsErr = String(e));
    await pause(8000);
    out.startedAfter = argvCount() - n0;
    out.tabs = await page.$$eval('[data-testid^="runtime-tab-"]', bs => bs.map(b => b.textContent));
    await page.click('[data-testid="agent-check-stop"]').catch(e => out.stopErr = String(e));
    await page.waitForSelector('[data-testid="agent-check"][data-phase="done"]', { timeout: 30000 }).catch(e => out.doneErr = String(e));
    out.panel = await page.$eval('[data-testid="agent-check"]', e => e.innerText);
    await page.screenshot({ path: __dirname + '/t2a-check-done.png' });
    out.stdinAfter = fs.readFileSync(S + '/fake/stdin.jsonl', 'utf8');
    out.reports = fs.existsSync(S + '/data/agent-checks') ? fs.readdirSync(S + '/data/agent-checks') : [];
    if (out.reports.length) out.report = JSON.parse(fs.readFileSync(S + '/data/agent-checks/' + out.reports.sort().pop(), 'utf8'));
    return out;
};
